"""The brief's measures (p.9), computed only from recorded evidence files. No database, network or model.

Inputs (all in docs/challenge/evidence/):
  scenario_run.json           the synthetic six-item scenario run (tests/test_scenario_run.py, SETUHAUL_RECORD_SCENARIO=1)
  snapshot_scenario_run.json  the supplied-snapshot ladder run (scripts/snapshot_scenario.py --record)
  integrity_proof.txt         N=20 integrity proof;  integrity_proof_n10.txt  N=10 integrity proof

Usage:  python scripts/scenario_measures.py            prints a Markdown report
        python scripts/scenario_measures.py --write    also writes docs/challenge/evidence/scenario_measures.md
A measure the evidence cannot support is printed as "not measured", with the reason. Nothing is estimated.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

EV = Path(__file__).resolve().parents[1] / "docs" / "challenge" / "evidence"


def outcome(path: list[str] | None) -> str | None:
    p = path or []
    if any(x.startswith("escalated:") for x in p):
        return "ESCALATED"
    if p == ["confirmation", "book"]:
        return "REQUESTED"
    if "options" in p:
        return "OPTIONS"
    return None


def per_driver(turns: list[dict], time_key: str) -> dict:
    """First message -> first usable outcome (options, a booking request or an escalation), per driver."""
    out: dict[str, dict] = {}
    for t in turns:
        d = t.get("driver") or t.get("case")
        if d in (None, "planner") or t.get("path") is None:
            continue
        s = out.setdefault(d, {"turns": 0, "asks": 0, "first_ms": t[time_key], "outcome": None, "ms": None})
        if s["outcome"]:
            continue
        s["turns"] += 1
        s["asks"] += sum(1 for x in t["path"] if x.startswith("ask"))
        o = outcome(t["path"])
        if o:
            s["outcome"], s["ms"] = o, t[time_key] - s["first_ms"] + t.get("turn_ms", 0)
    return out


def integrity(name: str) -> dict | None:
    f = EV / name
    if not f.exists():
        return None
    s = f.read_text(encoding="utf-8")
    m = re.search(r"totals: OK=(\d+) LOST=(\d+) other=(\d+)", s)
    q4 = re.search(r"Q4 pairs of active claims .*?: (\d+)", s)
    n = re.search(r"integrity proof - (\d+) drivers", s)
    res = re.search(r"RESULT: (\w+)\s+\((\d+)/(\d+) checks\)", s)
    return {"n": int(n.group(1)), "ok": int(m.group(1)), "lost": int(m.group(2)), "other": int(m.group(3)),
            "overlaps": int(q4.group(1)), "result": f"{res.group(1)} {res.group(2)}/{res.group(3)}"}


def main() -> int:
    syn = json.loads((EV / "scenario_run.json").read_text(encoding="utf-8"))
    snap = json.loads((EV / "snapshot_scenario_run.json").read_text(encoding="utf-8"))
    s_drv = per_driver(syn["turns"], "t_ms")
    for t in snap["turns"]:
        t["t0"] = 0
    k_drv = per_driver(snap["turns"], "t0")
    ints = [x for x in (integrity("integrity_proof_n10.txt"), integrity("integrity_proof.txt")) if x]

    L = ["# Brief measures (p.9), computed from recorded evidence",
         "",
         f"Generated by `python scripts/scenario_measures.py --write` from `scenario_run.json` (recorded "
         f"{syn['recorded_at']}), `snapshot_scenario_run.json` (recorded {snap['recorded_at']}) and the integrity "
         "proof outputs. Both scenario runs use the **deterministic rules reader** (no model call). Model-based "
         "extraction accuracy is measured separately, on the held-out set (`evals/`, `docs/3-build/README.md`).",
         "",
         "## Per driver: first message to first usable outcome",
         "",
         "| Run | Driver / case | Turns | Clarification questions | Outcome | Elapsed (ms) |",
         "|---|---|---:|---:|---|---:|"]
    for run, drv in (("synthetic", s_drv), ("snapshot", k_drv)):
        for d, s in drv.items():
            L.append(f"| {run} | {d} | {s['turns']} | {s['asks']} | {s['outcome'] or 'still asking (one turn recorded)'} "
                     f"| {s['ms'] if s['ms'] is not None else '-'} |")
    L += ["",
          "Elapsed, synthetic run: wall-clock between the driver's first message and the outcome inside one recorded "
          "test run, so it includes other drivers' interleaved turns and test setup. Elapsed, snapshot run: the "
          "measured processing time of the outcome turn (one message each). Neither is a network latency figure.",
          ""]
    done = [s for drv in (s_drv, k_drv) for s in drv.values() if s["outcome"]]
    auto = [s for s in done if s["outcome"] != "ESCALATED"]
    esc = [s for s in done if s["outcome"] == "ESCALATED"]
    esc_rows = [t for t in syn["turns"] + snap["turns"] if outcome(t.get("path")) == "ESCALATED"]
    complete = [t for t in esc_rows if (t.get("evidence") or {}).get("escalation", {}).get("handoff")]
    asks = sum(s["asks"] for s in done)
    L += ["## Measures", "", "| Measure (brief p.9) | Value | Evidence |", "|---|---|---|",
          f"| Time from first message to usable outcome | see table above; turns to outcome: "
          f"{', '.join(str(s['turns']) for s in done)} | both run files |",
          f"| Share resolved without manual takeover | {len(auto)} of {len(done)} cases that reached an outcome "
          f"({100 * len(auto) // max(len(done), 1)} %); the other {len(esc)} are the intended no-slot escalations | "
          "a planner approving a request is normal policy, not a takeover |"]
    for x in ints:
        L.append(f"| Conflicting or duplicate allocations (N={x['n']}) | {x['overlaps']} double bookings; {x['ok']} slot claim (hold, then pending "
                 f"request) for {x['n']} requests ({x['lost']} told LOST, {x['other']} other); {x['result']} | integrity proof |")
    held = next(t for t in syn["turns"] if t["item"] == 5 and t["driver"] == "C")
    L += [f"| Options later found infeasible | 1 in the synthetic run (driver C's chosen slot was taken before "
          f"confirmation); caught at commit, C told and re-offered. Active appointments on that slot afterwards: "
          f"{len(held['evidence']['active_appointments_on_that_slot'])} | `scenario_run.json` item 5 |",
          f"| No-slot escalations handled correctly | {len(complete)} of {len(esc_rows)} with a database-built "
          f"hand-off record (reason, mode, queue, ack SLA, what the driver was told) | item 6; snapshot L6 SHP1015 |",
          "| Average driver waiting after rescheduling | **not measured**: no gate-in or dock-in happens in either "
          "run (the snapshot date is in the past for the database) | - |",
          "| Warehouse slot utilisation | **not measured** in the scenario runs | - |",
          "| Priority-policy violations | **not measured as a count**. The facility proposal in item 7 kept the "
          "confirmed promise and changed 0 appointments | `scenario_run.json` item 7 |",
          f"| Driver clarification turns | {asks} clarification question(s) over {len(done)} resolved cases; the snapshot cases L2a "
          "and L2b stop after their one recorded question | both run files |", ""]
    text = "\n".join(L)
    sys.stdout.reconfigure(encoding="utf-8")
    print(text)
    if "--write" in sys.argv[1:]:
        (EV / "scenario_measures.md").write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
