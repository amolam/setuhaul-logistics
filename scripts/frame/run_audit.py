"""Run every check in data_audit.sql against the SetuHaul snapshot and write audit_results.md.

Usage:  python scripts/frame/run_audit.py [path/to/db]
Deterministic: no LLM involved. Re-running produces the same file.
"""
import re
import sqlite3
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DB = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parents[1] / "data" / "setuhaul_freight_operations.db"
SQL = (HERE / "data_audit.sql").read_text(encoding="utf-8")
OUT = HERE.parents[1] / "docs" / "1-frame" / "audit_results.md"

HEADER = re.compile(r"^-- @check (\w+) \| (\w+) \| (.+)$", re.M)


def parse_checks(sql: str):
    marks = list(HEADER.finditer(sql))
    for i, m in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(sql)
        body = sql[m.end():end].strip()
        yield m.group(1), m.group(2), m.group(3).strip(), body


def md_table(cols, rows, limit=25):
    def cell(v):
        return "" if v is None else str(v).replace("|", "\\|").replace("\n", " ")
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(cell(v) for v in r) + " |" for r in rows[:limit]]
    if len(rows) > limit:
        out.append(f"\n_{len(rows) - limit} more rows not shown_")
    return "\n".join(out)


def main():
    con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
    lines = ["# SetuHaul data audit results", "",
             f"Generated by `run_audit.py` from `{DB.name}`. A check with rows has evidence of the issue.", "",
             "| ID | Severity | Rows | Check |", "|---|---|---:|---|"]
    details = []
    for cid, sev, title, body in parse_checks(SQL):
        cur = con.execute(body)
        cols = [d[0] for d in cur.description]
        rows = cur.fetchall()
        lines.append(f"| [{cid}](#{cid.lower()}) | {sev} | {len(rows)} | {title} |")
        details += ["", f"## {cid}", "", f"**{sev}** - {title}", "", "```sql", body, "```", "",
                    md_table(cols, rows) if rows else "_No rows returned._"]
        print(f"{cid:4} {sev:6} rows={len(rows):3}  {title}")
    OUT.write_text("\n".join(lines + details) + "\n", encoding="utf-8")
    print(f"\nWrote {OUT}")


if __name__ == "__main__":
    main()
